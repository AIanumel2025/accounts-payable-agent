#!/usr/bin/env node
// Repeatable OpenAPI -> TypeScript contract pipeline (M11A task §4).
//
// `npm run api:generate` regenerates `openapi/openapi.json` and
// `src/types/api.generated.ts` from the real M10 FastAPI application and
// overwrites the committed snapshots.
//
// `npm run api:check` (used by CI) regenerates into a temp location and
// fails (non-zero exit) if the committed files would change -- this is the
// "contract drift" detector task §4 requires: if someone edits the FastAPI
// schema without regenerating the frontend types, CI catches it.
//
// Source of the schema, in order:
//   1. A live FastAPI instance at `${AP_AGENT_API_BASE_URL}/openapi.json`
//      (fast path when a backend is already running locally).
//   2. `python3 ../scripts/export_openapi_schema.py`, which builds the
//      FastAPI app in-process with a placeholder DSN that is never dialed
//      (`app.openapi()` needs no database connection) -- this is the path
//      CI and most local runs take, since it needs no running server.
//
// Never prints or embeds a real DSN, credential, tenant id or hostname.

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync, mkdirSync, existsSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const FRONTEND_ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const REPO_ROOT = path.dirname(FRONTEND_ROOT);

const COMMITTED_SCHEMA_PATH = path.join(FRONTEND_ROOT, "openapi", "openapi.json");
const COMMITTED_TYPES_PATH = path.join(FRONTEND_ROOT, "src", "types", "api.generated.ts");

const GENERATED_HEADER = `/* eslint-disable */
/**
 * AUTO-GENERATED by \`npm run api:generate\` from the M10 FastAPI OpenAPI
 * schema (openapi/openapi.json). Do not hand-edit -- edit the FastAPI
 * schema and regenerate instead (M11A task §4).
 */

`;

async function fetchLiveSchema() {
  const baseUrl = process.env.AP_AGENT_API_BASE_URL ?? "http://127.0.0.1:8000";
  try {
    const response = await fetch(`${baseUrl.replace(/\/$/, "")}/openapi.json`, {
      signal: AbortSignal.timeout(1500),
    });
    if (!response.ok) return null;
    return await response.text();
  } catch {
    return null;
  }
}

function exportSchemaViaPython(outputPath) {
  const pythonCandidates = [
    path.join(REPO_ROOT, ".venv-api-gen", "bin", "python3"),
    path.join(REPO_ROOT, ".venv", "bin", "python3"),
    "python3",
  ];

  let lastError;
  for (const pythonBin of pythonCandidates) {
    try {
      execFileSync(pythonBin, [path.join(REPO_ROOT, "scripts", "export_openapi_schema.py"), outputPath], {
        stdio: "pipe",
        cwd: REPO_ROOT,
      });
      return readFileSync(outputPath, "utf-8");
    } catch (error) {
      lastError = error;
    }
  }
  throw new Error(
    `Could not export the OpenAPI schema via Python (tried ${pythonCandidates.join(", ")}). ` +
      `Last error: ${lastError?.message ?? "unknown"}`,
  );
}

async function obtainSchemaText(workDir) {
  const live = await fetchLiveSchema();
  if (live) {
    console.log("api:generate -- using live FastAPI instance's /openapi.json");
    return live;
  }
  console.log("api:generate -- no live FastAPI instance reachable; exporting via Python in-process");
  const scratchPath = path.join(workDir, "openapi.json");
  return exportSchemaViaPython(scratchPath);
}

async function generateTypesText(schemaText) {
  const schema = JSON.parse(schemaText);
  const ast = await openapiTS(schema);
  return GENERATED_HEADER + astToString(ast);
}

function normalizeSchemaText(schemaText) {
  return JSON.stringify(JSON.parse(schemaText), null, 2) + "\n";
}

async function main() {
  const checkOnly = process.argv.includes("--check");
  const workDir = mkdtempSync(path.join(tmpdir(), "ap-agent-openapi-"));

  try {
    const schemaText = normalizeSchemaText(await obtainSchemaText(workDir));
    const typesText = await generateTypesText(schemaText);

    if (checkOnly) {
      const committedSchema = existsSync(COMMITTED_SCHEMA_PATH)
        ? readFileSync(COMMITTED_SCHEMA_PATH, "utf-8")
        : null;
      const committedTypes = existsSync(COMMITTED_TYPES_PATH) ? readFileSync(COMMITTED_TYPES_PATH, "utf-8") : null;

      const schemaDrift = committedSchema !== schemaText;
      const typesDrift = committedTypes !== typesText;

      if (schemaDrift || typesDrift) {
        console.error("api:check FAILED -- the committed OpenAPI contract is stale.");
        if (schemaDrift) console.error(`  - ${path.relative(FRONTEND_ROOT, COMMITTED_SCHEMA_PATH)} is out of date`);
        if (typesDrift) console.error(`  - ${path.relative(FRONTEND_ROOT, COMMITTED_TYPES_PATH)} is out of date`);
        console.error("Run `npm run api:generate` and commit the result.");
        process.exitCode = 1;
        return;
      }

      console.log("api:check OK -- generated types match the current FastAPI contract.");
      return;
    }

    mkdirSync(path.dirname(COMMITTED_SCHEMA_PATH), { recursive: true });
    mkdirSync(path.dirname(COMMITTED_TYPES_PATH), { recursive: true });
    writeFileSync(COMMITTED_SCHEMA_PATH, schemaText);
    writeFileSync(COMMITTED_TYPES_PATH, typesText);
    console.log(`Wrote ${path.relative(FRONTEND_ROOT, COMMITTED_SCHEMA_PATH)}`);
    console.log(`Wrote ${path.relative(FRONTEND_ROOT, COMMITTED_TYPES_PATH)}`);
  } finally {
    rmSync(workDir, { recursive: true, force: true });
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
